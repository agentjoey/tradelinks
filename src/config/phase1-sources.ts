/** Shared contract for the Experimental Amazon public BSR scrapers. */
function bsrSource(
  id: string,
  name: string,
  slug: string,
  refreshCron: string,
  categories: SourceContract["categories"],
  overrides: Partial<SourceContractInput> = {},
): SourceContractInput {
  return {
    id,
    name,
    url: `https://www.amazon.com/gp/bestsellers/${slug}/`,
    market: "US",
    platforms: ["AMAZON"],
    categories,
    authorityLevel: "PLATFORM_OFFICIAL",
    readiness: "EXPERIMENTAL",
    access: "PUBLIC",
    license: PLATFORM_LICENSE,
    fetchMethod: "SCRAPER",
    primaryEvidenceEligible: false,
    freshnessSlaMinutes: 1440,
    refreshCron,
    degradationPolicy: "Hide new demand cards when overdue; policy pages are never affected.",
    userPromise: "Best-seller rank movement observation only; no completeness claim.",
    enabled: true,
    fixture: "amz-bsr.html",
    selectors: { ...BSR_SELECTORS },
    ...overrides,
  };
}

