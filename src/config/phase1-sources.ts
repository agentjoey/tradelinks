/**
 * Phase 1 source registry — the single source of truth for readiness,
 * authority, collection method, refresh, SLA, degradation, and the exact
 * user promise of every source. Rows implement the Source Readiness Matrix
 * and the exact official allowlist in
 * docs/superpowers/plans/2026-07-23-tradelinks-phase1-foundation.md.
 *
 * Every out-of-scope legacy registry ID is kept here explicitly disabled
 * (`enabled: false`, readiness `UNAVAILABLE`) so "is this source in scope?"
 * is answerable from one place. Validation runs at module load: an enabled
 * source without SLA, cron, or an immutable fixture fails fast.
 */

