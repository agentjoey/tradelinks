    primaryEvidenceEligible: false,
    freshnessSlaMinutes: null,
    refreshCron: null,
    degradationPolicy: "Disabled for Phase 1; excluded from schedules and user promises.",
    userPromise: "No Phase 1 promise; this source is out of scope.",
